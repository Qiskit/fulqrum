import re
import runpy
from pathlib import Path

import pytest

from fulqrum.gpu import config

GPU_DIR = Path(config.__file__).parent
SOURCE_SUFFIXES = {".py", ".pyx", ".cpp", ".hpp", ".cu", ".cuh"}


@pytest.mark.parametrize(
    "text,expected",
    [("1", True), (" TRUE ", True), ("on", True), ("No", False), ("0", False)],
)
def test_booleans_accept_one_set_of_spellings(text, expected):
    assert config.parse_bool("FQ_X", text) is expected


def test_other_boolean_text_raises():
    with pytest.raises(ValueError, match="FQ_X"):
        config.parse_bool("FQ_X", "enabled")


def test_precedence_is_argument_then_environment_then_default():
    environ = {"FQ_EXCHANGE": "ring"}
    assert config.read("FQ_EXCHANGE", environ, value="two_level") == "two_level"
    assert config.read("FQ_EXCHANGE", environ) == "ring"
    assert config.read("FQ_EXCHANGE", {}) == "auto"
    assert config.read("FQ_EXCHANGE", {"FQ_EXCHANGE": "  "}) == "auto"


@pytest.mark.parametrize(
    "name,text",
    [
        ("FQ_HBM_FREE_FRACTION", "-0.1"),
        ("FQ_AABB_CLIQUE_MIN_MEMBERS", "1"),
        ("FQ_EXCHANGE", "nope"),
        ("FQ_BUILD_THREADS", "x"),
    ],
)
def test_out_of_range_or_unknown_values_raise(name, text):
    with pytest.raises(ValueError, match=name):
        config.read(name, {name: text})


def test_unknown_names_skip_known_and_private_names():
    environ = {
        "FQ_EXCHANGE": "ring",
        "FQ_TYPO": "1",
        "FULQRUM_OTHER": "x",
        "_FULQRUM_HOOK": "1",
        "PATH": "/",
    }
    assert config.unknown_names(environ) == ["FQ_TYPO", "FULQRUM_OTHER"]
    with pytest.warns(RuntimeWarning, match="FQ_TYPO"):
        config.warn_unknown_names(environ)


def test_every_name_read_by_the_gpu_module_is_registered():
    pattern = re.compile(r'"((?:_?FULQRUM_|FQ_)[A-Za-z0-9_]+)"')
    found = set()
    for path in GPU_DIR.rglob("*"):
        if path.suffix in SOURCE_SUFFIXES:
            text = path.read_text(errors="ignore")
            if path.suffix == ".cpp" and text.startswith("/* Generated by Cython"):
                continue
            found.update(pattern.findall(text))
    assert "FQ_HOST_MPI_CHUNK_MiB" in found
    missing = sorted(
        name
        for name in found
        if name not in config.REGISTRY and name not in config.NOT_VARIABLES
    )
    assert missing == []


def test_env_flags_document_is_current():
    project_root = GPU_DIR.parents[1]
    generator = project_root / "tools" / "generate_gpu_env_flags.py"
    if not generator.is_file():
        pytest.skip(
            "Developer guide generator is not installed with the runtime package"
        )
    generated = runpy.run_path(str(generator))["render_markdown"]()
    documented = set(re.findall(r"^\| `([^`]+)` ", generated, re.MULTILINE))
    assert documented == set(config.REGISTRY)
    guide = project_root.parent.parent / "execution_artifacts" / "ENV_FLAGS.md"
    if guide.is_file():
        assert guide.read_text() == generated, (
            f"regenerate with: python {generator} > {guide}"
        )


def test_snapshot_normalizes_checks_and_applies_overrides():
    snapshot = config.GpuConfig.from_environ(
        {"FQ_COMM_TIMING": "True", "FQ_EXCHANGE": "Ring", "FQ_BUILD_GPU": "1"},
        {"FQ_EXCHANGE": "two_level"},
    )
    assert dict(snapshot) == {"FQ_COMM_TIMING": "1", "FQ_EXCHANGE": "two_level"}
    assert snapshot.value("FQ_HBM_FREE_FRACTION") == 1.0
    assert (
        snapshot.digest()
        == config.GpuConfig.from_environ(
            {"FQ_EXCHANGE": "two_level", "FQ_COMM_TIMING": "yes"}
        ).digest()
    )
    with pytest.raises(ValueError, match="FQ_COMM_TIMING"):
        config.GpuConfig.from_environ({"FQ_COMM_TIMING": "maybe"})
    assert "FQ_MIXED_WINDOW" not in config.GpuConfig.from_environ(
        {"FQ_MIXED_WINDOW": "0"}
    )


def _tiny_operator(monkeypatch, environ, settings=None):
    import itertools

    import fulqrum as fq
    from fulqrum.gpu.distributed import _collective
    from fulqrum.gpu.distributed.dist_matvec_tile_resident import (
        TileGPUResidentHamiltonian,
    )
    from fulqrum.test.test_type2_differential import (
        NORB,
        ORDERINGS,
        bitstring,
        make_operator,
    )

    MPI = pytest.importorskip("mpi4py.MPI")
    for name, value in environ.items():
        monkeypatch.setenv(name, value)
    alpha, beta = ORDERINGS["block"]
    halves = [
        bitstring(occupied, NORB) for occupied in itertools.combinations(range(NORB), 2)
    ]
    qubit_op = make_operator(
        "aabb_uniform_singles", alpha, beta
    ).extended_jw_transformation()
    hsub = fq.SubspaceHamiltonian(qubit_op, fq.Subspace([halves, halves]))
    _collective.reset_for_testing()
    return TileGPUResidentHamiltonian(
        hsub,
        halves,
        halves,
        comm=MPI.COMM_SELF,
        comm_backend="host_mpi",
        config=settings,
    )


def test_operator_uses_the_given_configuration_over_the_environment(monkeypatch):
    pytest.importorskip("cupy")
    settings = config.GpuConfig.from_environ({}, {"FQ_AABB_CLIQUE_ENABLE": False})
    gpu = _tiny_operator(monkeypatch, {"FQ_AABB_CLIQUE_ENABLE": "1"}, settings)
    assert not gpu._aabb_parent_enabled
    record = gpu.run_record
    assert record["settings"] == {"FQ_AABB_CLIQUE_ENABLE": "0"}
    assert record["backend"] == "host_mpi" and record["exchange"] == "ring"
    assert {
        "config_digest",
        "exchange_digest",
        "kernel_params",
        "backend_reason",
    } <= set(record)


def test_operator_rejects_a_bad_environment_value(monkeypatch):
    pytest.importorskip("cupy")
    with pytest.raises(ValueError, match="FQ_EXCHANGE_DOUBLE_BUFFER"):
        _tiny_operator(monkeypatch, {"FQ_EXCHANGE_DOUBLE_BUFFER": "maybe"})


def test_build_job_registry_requires_positive_jobs():
    assert config.read("FQ_BUILD_PARALLEL", {}) == 1
    assert config.read("FQ_BUILD_PARALLEL", {"FQ_BUILD_PARALLEL": "4"}) == 4
    with pytest.raises(ValueError, match="FQ_BUILD_PARALLEL"):
        config.read("FQ_BUILD_PARALLEL", {"FQ_BUILD_PARALLEL": "0"})


def test_unused_primme_path_overrides_are_not_advertised():
    names = {"FQ_PRIMME_INCLUDEDIR", "FQ_PRIMME_LIBDIR", "FQ_PRIMME_LIBS"}
    assert not names.intersection(config.REGISTRY)
    assert config.unknown_names(dict.fromkeys(names, "unused")) == sorted(names)
    with pytest.raises(KeyError):
        config.GpuConfig.from_environ({}, {"FQ_PRIMME_INCLUDEDIR": "unused"})
